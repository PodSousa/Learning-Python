número = int(input(f'digite um número inteiro para associar a um dia da semana: '))

if número == 1:
    print(f'domingo')
elif número == 2:
    print(f'segunda')
elif número == 3:
    print(f'terça')
elif número == 4:
    print(f'quarta')
elif número == 5:
    print(f'quinta')
elif número == 6:
    print(f'sexta')
elif número == 7:
    print(f'sábado')
else:
    print(f'dia nenhum!')

